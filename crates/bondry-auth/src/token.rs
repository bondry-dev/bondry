/// A newly issued token secret that is redacted from debug output and zeroized on drop.
pub struct SecretToken {
    value: Zeroizing<String>,
}

impl SecretToken {
    /// Exposes the token for the deliberate act of copying it to a client.
    #[must_use]
    pub fn expose(&self) -> &str {
        self.value.as_str()
    }
}

impl fmt::Debug for SecretToken {
    fn fmt(&self, formatter: &mut fmt::Formatter<'_>) -> fmt::Result {
        formatter.write_str("SecretToken([REDACTED])")
    }
}

/// A token returned once at issuance or rotation time.
pub struct IssuedToken {
    metadata: TokenMetadata,
    secret: SecretToken,
}

impl IssuedToken {
    pub(crate) const fn new(metadata: TokenMetadata, secret: SecretToken) -> Self {
        Self { metadata, secret }
    }

    /// Returns the non-secret token metadata.
    #[must_use]
    pub const fn metadata(&self) -> &TokenMetadata {
        &self.metadata
    }

    /// Returns the one-time token secret.
    #[must_use]
    pub const fn secret(&self) -> &SecretToken {
        &self.secret
    }
}

pub(crate) trait RandomSource: Send + Sync {
    fn fill(&self, destination: &mut [u8]) -> Result<(), RandomError>;
}

pub(crate) struct SystemRandom;

impl RandomSource for SystemRandom {
    fn fill(&self, destination: &mut [u8]) -> Result<(), RandomError> {
        getrandom::fill(destination).map_err(|_| RandomError)
    }
}

pub(crate) struct RandomError;

pub(crate) struct GeneratedToken {
    pub(crate) id: TokenId,
    pub(crate) digest: TokenDigest,
    pub(crate) secret: SecretToken,
}

impl GeneratedToken {
    pub(crate) fn generate(random: &dyn RandomSource) -> Result<Self, RandomError> {
        let mut id_bytes = [0_u8; TOKEN_ID_RANDOM_BYTES];
        let mut secret_bytes = Zeroizing::new([0_u8; TOKEN_SECRET_BYTES]);
        random.fill(&mut id_bytes)?;
        random.fill(secret_bytes.as_mut())?;

        let id = TokenId::from_random_bytes(&id_bytes).map_err(|_| RandomError)?;
        let digest = TokenDigest::from_secret(secret_bytes.as_ref());
        let encoded_secret = Zeroizing::new(URL_SAFE_NO_PAD.encode(secret_bytes.as_ref()));
        let value = Zeroizing::new(format!(
            "{TOKEN_FORMAT}.{}.{}",
            id.as_str(),
            encoded_secret.as_str()
        ));
        Ok(Self {
            id,
            digest,
            secret: SecretToken { value },
        })
    }
}

pub(crate) struct PresentedToken {
    pub(crate) id: TokenId,
    pub(crate) digest: TokenDigest,
}

impl PresentedToken {
    pub(crate) fn parse(value: &str) -> Result<Self, ()> {
        let mut parts = value.split('.');
        let format = parts.next().ok_or(())?;
        let id = parts.next().ok_or(())?;
        let encoded_secret = parts.next().ok_or(())?;
        if parts.next().is_some() || format != TOKEN_FORMAT {
            return Err(());
        }

        let id = TokenId::new(id).map_err(|_| ())?;
        let secret = Zeroizing::new(URL_SAFE_NO_PAD.decode(encoded_secret).map_err(|_| ())?);
        if secret.len() != TOKEN_SECRET_BYTES {
            return Err(());
        }
        Ok(Self {
            id,
            digest: TokenDigest::from_secret(secret.as_ref()),
        })
    }

    pub(crate) fn matches(&self, stored: &TokenDigest) -> bool {
        stored.matches(&self.digest)
    }
}

#[cfg(test)]
mod tests {
    use base64::{Engine as _, engine::general_purpose::URL_SAFE_NO_PAD};

    use super::{
        GeneratedToken, PresentedToken, RandomError, RandomSource, TokenDigest, TokenId,
        TokenIdError, TokenLabel, TokenLabelError,
    };

    struct FixedRandom(u8);

    impl RandomSource for FixedRandom {
        fn fill(&self, destination: &mut [u8]) -> Result<(), RandomError> {
            destination.fill(self.0);
            Ok(())
        }
    }

    #[test]
    fn generated_tokens_parse_and_match_their_digest() -> Result<(), Box<dyn std::error::Error>> {
        let generated = GeneratedToken::generate(&FixedRandom(7))
            .map_err(|_| std::io::Error::other("deterministic generation unexpectedly failed"))?;
        let presented = PresentedToken::parse(generated.secret.expose())
            .map_err(|()| std::io::Error::other("generated token did not parse"))?;

        assert_eq!(presented.id, generated.id);
        assert!(presented.matches(&generated.digest));
        assert_eq!(format!("{:?}", generated.digest), "TokenDigest([REDACTED])");
        Ok(())
    }

    #[test]
    fn token_identifiers_are_strict_and_canonical() -> Result<(), TokenIdError> {
        let encoded = URL_SAFE_NO_PAD.encode([0_u8; 16]);
        let id = TokenId::new(format!("token_{encoded}"))?;
        assert!(id.as_str().starts_with("token_"));

        for invalid in ["", "token_", "client_AAAAAAAAAAAAAAAAAAAAAA", "token_***"] {
            assert_eq!(TokenId::new(invalid), Err(TokenIdError::Invalid));
        }
        Ok(())
    }

    #[test]
    fn presented_tokens_reject_noncanonical_shapes() {
        let id = format!("token_{}", URL_SAFE_NO_PAD.encode([0_u8; 16]));
        let secret = URL_SAFE_NO_PAD.encode([0_u8; 32]);
        for invalid in [
            format!("bondry_v2.{id}.{secret}"),
            format!("bondry_v1.{id}.{secret}.extra"),
            format!("bondry_v1.{id}.short"),
            format!("bondry_v1.invalid.{secret}"),
        ] {
            assert!(PresentedToken::parse(&invalid).is_err());
        }
    }

    #[test]
    fn token_labels_are_trimmed_and_bounded() -> Result<(), TokenLabelError> {
        assert_eq!(TokenLabel::new("  Primary  ")?.as_str(), "Primary");
        assert_eq!(TokenLabel::new(" \n "), Err(TokenLabelError::Empty));
        assert_eq!(
            TokenLabel::new("é".repeat(65)),
            Err(TokenLabelError::TooLong)
        );
        Ok(())
    }

    #[test]
    fn digest_comparison_rejects_different_values() {
        let first = TokenDigest::from_bytes([1_u8; 32]);
        let second = TokenDigest::from_bytes([2_u8; 32]);
        assert!(first.matches(&first));
        assert!(!first.matches(&second));
    }
}
