use std::fmt;

use base64::{Engine as _, engine::general_purpose::URL_SAFE_NO_PAD};
use bondry_core::PrincipalId;
use sha2::{Digest, Sha256};
use subtle::ConstantTimeEq;
use thiserror::Error;
use zeroize::Zeroizing;

const TOKEN_FORMAT: &str = "bondry_v1";
const TOKEN_ID_PREFIX: &str = "token_";
const TOKEN_ID_RANDOM_BYTES: usize = 16;
const TOKEN_SECRET_BYTES: usize = 32;
const MAX_TOKEN_LABEL_LENGTH: usize = 128;

/// A validated public identifier for an access token.
#[derive(Clone, Debug, Eq, Hash, Ord, PartialEq, PartialOrd)]
pub struct TokenId(String);

impl TokenId {
    /// Parses a token identifier generated by Bondry.
    pub fn new(value: impl Into<String>) -> Result<Self, TokenIdError> {
        let value = value.into();
        let encoded = value
            .strip_prefix(TOKEN_ID_PREFIX)
            .ok_or(TokenIdError::Invalid)?;
        let bytes = URL_SAFE_NO_PAD
            .decode(encoded)
            .map_err(|_| TokenIdError::Invalid)?;
        if bytes.len() != TOKEN_ID_RANDOM_BYTES {
            return Err(TokenIdError::Invalid);
        }
        Ok(Self(value))
    }

    /// Returns the token identifier.
    #[must_use]
    pub fn as_str(&self) -> &str {
        &self.0
    }

    fn from_random_bytes(bytes: &[u8; TOKEN_ID_RANDOM_BYTES]) -> Result<Self, TokenIdError> {
        Self::new(format!(
            "{TOKEN_ID_PREFIX}{}",
            URL_SAFE_NO_PAD.encode(bytes)
        ))
    }
}

/// An invalid token identifier.
#[derive(Clone, Copy, Debug, Eq, Error, PartialEq)]
pub enum TokenIdError {
    /// The identifier is not a canonical Bondry token identifier.
    #[error("invalid token identifier")]
    Invalid,
}

/// An optional administrative label for a token.
#[derive(Clone, Debug, Eq, Hash, PartialEq)]
pub struct TokenLabel(String);

impl TokenLabel {
    /// Creates a trimmed, non-empty token label.
    pub fn new(value: impl Into<String>) -> Result<Self, TokenLabelError> {
        let value = value.into();
        let value = value.trim();
        if value.is_empty() {
            return Err(TokenLabelError::Empty);
        }
        if value.len() > MAX_TOKEN_LABEL_LENGTH {
            return Err(TokenLabelError::TooLong);
        }
        Ok(Self(value.to_owned()))
    }

    /// Returns the administrative label.
    #[must_use]
    pub fn as_str(&self) -> &str {
        &self.0
    }
}

/// An invalid token label.
#[derive(Clone, Copy, Debug, Eq, Error, PartialEq)]
pub enum TokenLabelError {
    /// The label is empty after trimming.
    #[error("a token label cannot be empty")]
    Empty,
    /// The label exceeds the supported encoded length.
    #[error("a token label cannot exceed {MAX_TOKEN_LABEL_LENGTH} bytes")]
    TooLong,
}

/// A SHA-256 digest of a 256-bit random token secret.
#[derive(Clone, Eq, PartialEq)]
pub struct TokenDigest([u8; 32]);

impl TokenDigest {
    /// Reconstructs a digest from trusted persistent state.
    #[must_use]
    pub const fn from_bytes(bytes: [u8; 32]) -> Self {
        Self(bytes)
    }

    /// Returns the digest bytes for persistence.
    #[must_use]
    pub const fn as_bytes(&self) -> &[u8; 32] {
        &self.0
    }

    fn from_secret(secret: &[u8]) -> Self {
        Self(Sha256::digest(secret).into())
    }

    fn matches(&self, candidate: &Self) -> bool {
        bool::from(self.0.ct_eq(&candidate.0))
    }
}

impl fmt::Debug for TokenDigest {
    fn fmt(&self, formatter: &mut fmt::Formatter<'_>) -> fmt::Result {
        formatter.write_str("TokenDigest([REDACTED])")
    }
}

/// A stored token record that never contains the presented secret.
#[derive(Clone, Eq, PartialEq)]
pub struct TokenRecord {
    id: TokenId,
    client: PrincipalId,
    label: Option<TokenLabel>,
    digest: TokenDigest,
    created_at_unix_seconds: i64,
    expires_at_unix_seconds: Option<i64>,
    revoked_at_unix_seconds: Option<i64>,
}

impl TokenRecord {
    /// Reconstructs a token from trusted persistent state.
    #[must_use]
    pub const fn from_stored_parts(
        id: TokenId,
        client: PrincipalId,
        label: Option<TokenLabel>,
        digest: TokenDigest,
        created_at_unix_seconds: i64,
        expires_at_unix_seconds: Option<i64>,
        revoked_at_unix_seconds: Option<i64>,
    ) -> Self {
        Self {
            id,
            client,
            label,
            digest,
            created_at_unix_seconds,
            expires_at_unix_seconds,
            revoked_at_unix_seconds,
        }
    }

    /// Returns the token identifier.
    #[must_use]
    pub const fn id(&self) -> &TokenId {
        &self.id
    }

    /// Returns the owning client principal.
    #[must_use]
    pub const fn client(&self) -> &PrincipalId {
        &self.client
    }

    /// Returns the optional administrative label.
    #[must_use]
    pub const fn label(&self) -> Option<&TokenLabel> {
        self.label.as_ref()
    }

    /// Returns the stored secret digest.
    #[must_use]
    pub const fn digest(&self) -> &TokenDigest {
        &self.digest
    }

    /// Returns the creation time as Unix seconds.
    #[must_use]
    pub const fn created_at_unix_seconds(&self) -> i64 {
        self.created_at_unix_seconds
    }

    /// Returns the optional expiration time as Unix seconds.
    #[must_use]
    pub const fn expires_at_unix_seconds(&self) -> Option<i64> {
        self.expires_at_unix_seconds
    }

    /// Returns the optional revocation time as Unix seconds.
    #[must_use]
    pub const fn revoked_at_unix_seconds(&self) -> Option<i64> {
        self.revoked_at_unix_seconds
    }

    /// Marks the stored record as revoked at the given Unix time.
    pub fn mark_revoked(&mut self, revoked_at_unix_seconds: i64) {
        self.revoked_at_unix_seconds = Some(revoked_at_unix_seconds);
    }

    /// Returns whether the token is neither revoked nor expired.
    #[must_use]
    pub fn is_active_at(&self, unix_seconds: i64) -> bool {
        self.revoked_at_unix_seconds.is_none()
            && self
                .expires_at_unix_seconds
                .is_none_or(|expires_at| unix_seconds < expires_at)
    }

    /// Returns a copy of the non-secret administrative metadata.
    #[must_use]
    pub fn metadata(&self) -> TokenMetadata {
        TokenMetadata {
            id: self.id.clone(),
            client: self.client.clone(),
            label: self.label.clone(),
            created_at_unix_seconds: self.created_at_unix_seconds,
            expires_at_unix_seconds: self.expires_at_unix_seconds,
            revoked_at_unix_seconds: self.revoked_at_unix_seconds,
        }
    }
}

impl fmt::Debug for TokenRecord {
    fn fmt(&self, formatter: &mut fmt::Formatter<'_>) -> fmt::Result {
        formatter
            .debug_struct("TokenRecord")
            .field("id", &self.id)
            .field("client", &self.client)
            .field("label", &self.label)
            .field("digest", &"[REDACTED]")
            .field("created_at_unix_seconds", &self.created_at_unix_seconds)
            .field("expires_at_unix_seconds", &self.expires_at_unix_seconds)
            .field("revoked_at_unix_seconds", &self.revoked_at_unix_seconds)
            .finish()
    }
}

